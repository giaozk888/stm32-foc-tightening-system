function c=build_dob_simulink()
c=dob_config();if ~isfolder(c.build),mkdir(c.build);end
assert(license('test','Simulink')==1,'Simulink license required');
common=fullfile(c.repo,'firmware_common');native=fullfile(c.root,'native');
% Assert reviewed constants/profile before using the SPEED adapter. A changed
% owner must trigger re-review, not silently drift from this offline adapter.
main=fileread(fullfile(c.repo,'foc2_app_a','Core','Src','main.c'));
checks={'SPEED_KP_A_PER_RPM',.003;'SPEED_KI_A_PER_RPM_S',.020; ...
 'SPEED_INT_LIMIT_A',.35;'SPEED_FILTER_TAU_S',.020; ...
 'SPEED_OVERSPEED_BLEED_ERR_RPM',5;'SPEED_OVERSPEED_BLEED_MIN_SPD_RPM',5; ...
 'SPEED_OVERSPEED_I_BLEED_A_PER_S',5};
for k=1:size(checks,1)
 v=regexp(main,['#define\s+',checks{k,1},'\s+([\d.]+)f'],'tokens','once');
 assert(~isempty(v)&&str2double(v{1})==checks{k,2},'SPEED owner changed: %s',checks{k,1});
end
presets=jsondecode(fileread(fullfile(c.repo,'foc2_app_a','CMakePresets.json')));
% Current preset inheritance is captured; base parameters explicitly checked.
cache=fileread(fullfile(c.repo,'foc2_app_a','build', ...
 'TighteningDob025Contact20Observe10Candidate','CMakeCache.txt'));
for pair={'FOC_ACCEL_FF_KA_A_PER_RPM_S:STRING=0.000046875', ...
 'FOC_FRICTION_I_A:STRING=0.105','FOC_SPEED_SB3_DISABLE_CANDIDATE:BOOL=ON', ...
 'FOC_SPEED_BUMPLESS:BOOL=ON','FOC_SPEED_PI_ANTI_WINDUP:BOOL=ON'}
 assert(contains(cache,pair{1}),'Reviewed candidate profile changed: %s',pair{1});
end
flags={'FOC_DOB_SPIKE_ADMISSION=1','FOC_DOB_ADMISSION_START_GUARD=1', ...
 'FOC_DOB_DIRECT_JUMP_REJECT=1','FOC_DOB_RECOVERABLE_ADMISSION=1', ...
 'FOC_DOB_PERSISTENT_QUALITY=1','FOC_DOB_ID_PRE_LPF_QUALITY=1', ...
 'FOC_DOB_NORMAL_CONTROL=1','FOC_DOB_CONTACT20_OBSERVE10=1', ...
 'FOC_DOB_ID_TRACE=1','DOB_ADMIT_JUMP_A=.200f','DOB_FB_GAIN=dob_host_gain'};
sources={fullfile(native,'dob_host.c'),fullfile(common,'mechanical_dob_monitor.c'), ...
 fullfile(common,'speed_scurve.c'),fullfile(common,'speed_accel_feedforward.c'), ...
 fullfile(common,'speed_friction_compensation.c')};
gcc='D:\Qt\Tools\mingw1310_64\bin\gcc.exe';assert(isfile(gcc),'Configure host GCC path');
cmd=sprintf('"%s" -std=c11 -O2 -Wall -Wextra -Werror -shared -include "%s" -I"%s" ', ...
 gcc,fullfile(native,'host_compat.h'),common);
for k=1:numel(flags),cmd=[cmd,' -D',flags{k}];end %#ok<AGROW>
for k=1:numel(sources),cmd=[cmd,' "',sources{k},'"'];end %#ok<AGROW>
cmd=[cmd,' -o "',fullfile(c.build,'dob_host.dll'),'"'];
[status,txt]=system(cmd);assert(status==0,'Host C compile failed: %s',txt);
mex('-silent','-outdir',c.build,fullfile(native,'dob_bridge_mex.c'));
mex('-silent','-outdir',c.build,fullfile(native,'dob_controller_sfun.c'));
mex('-silent','-outdir',c.build,fullfile(native,'dob_plant_sfun.c'));
addpath(c.root,c.build);
% Keep a source manifest and a firmware baseline to prove no source mutation.
files=[sources,cellstr(fullfile(common,["mechanical_dob_shadow.h", ...
 "mechanical_dob_monitor.h","dob_current_admission.h","dob_id_pre_lpf_quality.h", ...
 "dob_feedback_candidate.h","dob_contact20_observe10.h","speed_bumpless.h", ...
 "speed_startup_brake.h","speed_pi_anti_windup.h","speed_scurve.h", ...
 "speed_accel_feedforward.h","speed_friction_compensation.h"])), ...
 {fullfile(c.repo,'foc2_app_a','Core','Src','main.c'),fullfile(c.repo,'foc2_app_b','Core','Src','main.c')}];
% Freeze harness as well as MCU-side controller inputs. Current dirty-tree
% contents are the baseline; never compare to HEAD and discard user changes.
patterns={fullfile(c.root,'*.m'),fullfile(c.root,'tests','*.m'), ...
 fullfile(native,'*.c'),fullfile(native,'*.h'),fullfile(common,'*.h'), ...
 fullfile(common,'*.c'),fullfile(common,'*.inc')};
for p=patterns
 list=dir(p{1});for j=1:numel(list),files{end+1}=fullfile(list(j).folder,list(j).name);end %#ok<AGROW>
end
for app={'foc2_app_a','foc2_app_b'}
 for relative={'CMakeLists.txt','CMakePresets.json'}
  files{end+1}=fullfile(c.repo,app{1},relative{1}); %#ok<AGROW>
 end
end
files=unique(files,'stable');
manifest=struct('matlab',version,'flags',{flags},'hardware_access',false, ...
 'physical_performance_validated',false,'sources',struct([]));
for k=1:numel(files)
 manifest.sources(k).path=files{k};manifest.sources(k).sha256=dob_sha256(files{k});
end
manifest.preset_count=numel(presets.configurePresets);
dob_write_json(fullfile(c.build,'source_manifest.json'),manifest);
build_model(c);
fprintf('PASS: original C host DLL, 3 MEX modules, Simulink model built\n');
end

function build_model(c)
if bdIsLoaded(c.model),close_system(c.model,0);end
new_system(c.model);set_param(c.model,'SolverType','Fixed-step','Solver','FixedStepDiscrete', ...
 'FixedStep','0.00005','StopTime',num2str(c.stop_s),'ReturnWorkspaceOutputs','on');
add_block('simulink/Sources/From Workspace',[c.model '/Scenario_Measurement_Injection'], ...
 'VariableName','stimulus','Interpolate','off','OutputAfterFinalValue','Holding final value', ...
 'SampleTime','.001','Position',[30 40 190 85]);
add_block('simulink/Sources/From Workspace',[c.model '/Independent_Load_GroundTruth_A'], ...
 'VariableName','load_truth','Interpolate','off','OutputAfterFinalValue','Holding final value', ...
 'SampleTime','.00005','Position',[30 390 200 430]);
add_block('simulink/Signal Routing/Demux',[c.model '/Exogenous'], ...
 'Outputs','8','Position',[220 20 225 280]);
add_block('simulink/Signal Routing/Mux',[c.model '/Controller_Inputs'], ...
 'Inputs','10','Position',[350 30 355 310]);
add_block('simulink/User-Defined Functions/S-Function',[c.model '/Original_C_SpeedPI_Scurve_DOB_Quality'], ...
 'FunctionName','dob_controller_sfun','Parameters','host_dll, run_config','Position',[400 80 640 150]);
add_block('simulink/Signal Routing/Selector',[c.model '/Total_Iq_Limited'], ...
 'NumberOfDimensions','1','IndexMode','One-based','Indices','8','InputPortWidth','33', ...
 'Position',[680 90 740 130]);
add_block('simulink/Discrete/Zero-Order Hold',[c.model '/PWM_Command_ZOH'], ...
 'SampleTime','.00005','Position',[780 90 845 130]);
add_block('simulink/Discrete/Unit Delay',[c.model '/One_PWM_Cycle_50us'], ...
 'SampleTime','.00005','InitialCondition','0','Position',[880 90 955 130]);
add_block('simulink/Signal Routing/Mux',[c.model '/Plant_Inputs'], ...
 'Inputs','2','Position',[1000 90 1005 180]);
add_block('simulink/User-Defined Functions/S-Function',[c.model '/Mechanical_Plant_Assumed_CurrentLag'], ...
 'FunctionName','dob_plant_sfun','Parameters','plant_parameters','Position',[1040 90 1280 160]);
add_block('simulink/Signal Routing/Demux',[c.model '/Physical_States'], ...
 'Outputs','3','Position',[1320 80 1325 180]);
add_block('simulink/Sinks/To Workspace',[c.model '/Control_Log'], ...
 'VariableName','control_log','SaveFormat','Timeseries','SampleTime','.001', ...
 'MaxDataPoints','inf','Position',[670 240 790 275]);
add_block('simulink/Sinks/To Workspace',[c.model '/Truth_Log'], ...
 'VariableName','truth_log','SaveFormat','Timeseries','SampleTime','.001', ...
 'MaxDataPoints','inf','Position',[1330 240 1440 280]);
add_block('simulink/Sinks/To Workspace',[c.model '/Actually_Consumed_Inputs'], ...
 'VariableName','input_log','SaveFormat','Timeseries','SampleTime','.001', ...
 'MaxDataPoints','inf','Position',[370 330 530 365]);
add_block('simulink/Sinks/To Workspace',[c.model '/Load_Truth_Recorded'], ...
 'VariableName','load_log','SaveFormat','Timeseries','SampleTime','.001', ...
 'MaxDataPoints','inf','Position',[260 400 400 435]);
add_line(c.model,'Scenario_Measurement_Injection/1','Exogenous/1');
add_line(c.model,'Exogenous/1','Controller_Inputs/1');
for k=2:8,add_line(c.model,sprintf('Exogenous/%d',k),sprintf('Controller_Inputs/%d',k+2),'autorouting','on');end
add_line(c.model,'Physical_States/1','Controller_Inputs/2','autorouting','on');
add_line(c.model,'Physical_States/2','Controller_Inputs/3','autorouting','on');
add_line(c.model,'Controller_Inputs/1','Original_C_SpeedPI_Scurve_DOB_Quality/1');
add_line(c.model,'Controller_Inputs/1','Actually_Consumed_Inputs/1','autorouting','on');
add_line(c.model,'Original_C_SpeedPI_Scurve_DOB_Quality/1','Total_Iq_Limited/1');
add_line(c.model,'Original_C_SpeedPI_Scurve_DOB_Quality/1','Control_Log/1','autorouting','on');
add_line(c.model,'Total_Iq_Limited/1','PWM_Command_ZOH/1');
add_line(c.model,'PWM_Command_ZOH/1','One_PWM_Cycle_50us/1');
add_line(c.model,'One_PWM_Cycle_50us/1','Plant_Inputs/1');
add_line(c.model,'Independent_Load_GroundTruth_A/1','Plant_Inputs/2','autorouting','on');
add_line(c.model,'Independent_Load_GroundTruth_A/1','Load_Truth_Recorded/1','autorouting','on');
add_line(c.model,'Plant_Inputs/1','Mechanical_Plant_Assumed_CurrentLag/1');
add_line(c.model,'Mechanical_Plant_Assumed_CurrentLag/1','Physical_States/1');
add_line(c.model,'Mechanical_Plant_Assumed_CurrentLag/1','Truth_Log/1','autorouting','on');
% Leave valid offline defaults so the saved SLX can also run interactively.
[stimulus,load_truth]=dob_scenario(c,'step',101);
ws=get_param(c.model,'ModelWorkspace');
assignin(ws,'stimulus',stimulus);assignin(ws,'load_truth',load_truth);
assignin(ws,'host_dll',fullfile(c.build,'dob_host.dll'));
assignin(ws,'run_config',[0,0,.025]);assignin(ws,'plant_parameters',c.plant_vector);
save_system(c.model,fullfile(c.build,[c.model '.slx']));
end
