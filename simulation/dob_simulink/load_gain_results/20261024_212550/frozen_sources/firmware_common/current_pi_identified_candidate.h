#ifndef CURRENT_PI_IDENTIFIED_CANDIDATE_H
#define CURRENT_PI_IDENTIFIED_CANDIDATE_H

/* User-selected, UNQUALIFIED estimates; A-only opt-in, never persistent PI. */
#ifndef FOC_CURRENT_PI_IDENTIFIED_ENABLE
#define FOC_CURRENT_PI_IDENTIFIED_ENABLE 0
#endif
#define CURRENT_PI_CANDIDATE_RS_OHM 0.78f
#define CURRENT_PI_CANDIDATE_LD_H 0.00002003f
#define CURRENT_PI_CANDIDATE_LQ_H 0.00001118f
#ifndef CURRENT_PI_CANDIDATE_BANDWIDTH_HZ
#define CURRENT_PI_CANDIDATE_BANDWIDTH_HZ 300.0f
#endif
#define CURRENT_PI_CANDIDATE_WC (6.283185307179586f * CURRENT_PI_CANDIDATE_BANDWIDTH_HZ)

#if defined(FOC_CURRENT_STEP_AB_DIAG)
extern unsigned current_step_pi_new;
#define FOC_CURRENT_KP_D_V_PER_A (current_step_pi_new ? CURRENT_PI_CANDIDATE_LD_H * CURRENT_PI_CANDIDATE_WC : FOC_CURRENT_KP_V_PER_A)
#define FOC_CURRENT_KP_Q_V_PER_A (current_step_pi_new ? CURRENT_PI_CANDIDATE_LQ_H * CURRENT_PI_CANDIDATE_WC : FOC_CURRENT_KP_V_PER_A)
#define FOC_CURRENT_KI_D_V_PER_AS (current_step_pi_new ? CURRENT_PI_CANDIDATE_RS_OHM * CURRENT_PI_CANDIDATE_WC : FOC_CURRENT_KI_V_PER_AS)
#define FOC_CURRENT_KI_Q_V_PER_AS (current_step_pi_new ? CURRENT_PI_CANDIDATE_RS_OHM * CURRENT_PI_CANDIDATE_WC : FOC_CURRENT_KI_V_PER_AS)
#elif FOC_CURRENT_PI_IDENTIFIED_ENABLE
#define FOC_CURRENT_KP_D_V_PER_A (CURRENT_PI_CANDIDATE_LD_H * CURRENT_PI_CANDIDATE_WC)
#define FOC_CURRENT_KP_Q_V_PER_A (CURRENT_PI_CANDIDATE_LQ_H * CURRENT_PI_CANDIDATE_WC)
#define FOC_CURRENT_KI_D_V_PER_AS (CURRENT_PI_CANDIDATE_RS_OHM * CURRENT_PI_CANDIDATE_WC)
#define FOC_CURRENT_KI_Q_V_PER_AS (CURRENT_PI_CANDIDATE_RS_OHM * CURRENT_PI_CANDIDATE_WC)
#else
/* Existing literals/order are retained when the candidate is disabled. */
#define FOC_CURRENT_KP_D_V_PER_A FOC_CURRENT_KP_V_PER_A
#define FOC_CURRENT_KP_Q_V_PER_A FOC_CURRENT_KP_V_PER_A
#define FOC_CURRENT_KI_D_V_PER_AS FOC_CURRENT_KI_V_PER_AS
#define FOC_CURRENT_KI_Q_V_PER_AS FOC_CURRENT_KI_V_PER_AS
#endif
#endif
